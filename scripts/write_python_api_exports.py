"""Generate typing stubs from the canonical lazy export authority."""

from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path
from types import ModuleType

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "python" / "src" / "shardloom"
AUTHORITY = PACKAGE / "_exports.py"
TARGETS = {
    "__init__.pyi": None,
    "diagnostics.pyi": "diagnostics",
    "testing.pyi": "testing",
}


def load_authority() -> ModuleType:
    spec = importlib.util.spec_from_file_location("_shardloom_exports", AUTHORITY)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load export authority at {AUTHORITY}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def render_stub(exports: dict[str, tuple[str, str]], audience: str | None) -> str:
    selected = {
        name: export for name, export in exports.items()
        if export[1] == ("application" if audience is None else audience)
    }
    by_module: dict[str, list[str]] = {}
    for name, (module, _kind) in selected.items():
        by_module.setdefault(module, []).append(name)

    lines = [
        "# SPDX-License-Identifier: Apache-2.0",
        "# Generated by scripts/write_python_api_exports.py; do not edit.",
        "from __future__ import annotations",
        "",
    ]
    if audience is None:
        lines.extend(
            (
                "from typing import Any",
                "from . import diagnostics as diagnostics",
                "from . import native as native",
                "from . import testing as testing",
            )
        )
    for module in sorted(by_module):
        for name in sorted(by_module[module]):
            lines.append(f"from .{module} import {name} as {name}")
    if audience is None:
        public = sorted({
            "__version__",
            "native",
            "diagnostics",
            "testing",
            *sorted(
                name
                for name, (_module, kind) in exports.items()
                if kind == "application" and name != "__version__"
            ),
        })
        lines.extend(("", f"__all__ = {tuple(public)!r}"))
        lines.extend((
            "", "# Named legacy imports remain available at runtime during migration.",
            "# Their precise types live in diagnostics/testing; keep IDE discovery curated.",
            "def __getattr__(name: str) -> Any: ...",
        ))
    else:
        lines.extend(("", f"__all__ = {tuple(sorted(selected))!r}"))
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if generated stubs are stale"
    )
    args = parser.parse_args()
    exports = dict(load_authority().EXPORTS)
    stale: list[str] = []
    for filename, audience in TARGETS.items():
        path = PACKAGE / filename
        expected = render_stub(exports, audience)
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(expected, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        for path in stale:
            print(f"stale generated stub: {path}")
        return 1
    if args.check:
        print("Python API stubs are current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

