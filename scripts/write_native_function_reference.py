"""Generate scalar-function documentation from the actual native definitions.

Regenerate with --native-library after rebuilding. Source-only --check validates
the saved definition identity and rendering without importing a native library.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.machinery
import importlib.util
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path("shardloom-core/src/expression_builtins.rs")
TARGET = Path("docs/reference/native-scalar-functions.json")


def snapshot(root: Path, native_library: Path | None = None) -> dict:
    identity = hashlib.sha256((root / SOURCE).read_bytes()).hexdigest()
    if native_library is None:
        data = json.loads((root / TARGET).read_text())
        if data.get("source_sha256") != identity:
            raise ValueError("scalar definitions changed; rebuild and regenerate with --native-library")
    else:
        sys.path.insert(0, str(root / "python/src"))
        import shardloom
        name = "shardloom._native"
        library = native_library.resolve()
        loader = importlib.machinery.ExtensionFileLoader(name, str(library))
        spec = importlib.util.spec_from_file_location(name, library, loader=loader)
        if spec is None or spec.loader is None:
            raise ValueError("could not load the native library")
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
        if module.__version__ != shardloom.__version__:
            raise ValueError("native library and source package versions differ")
        data = {"schema_version": "shardloom.native_scalar_functions.v1",
                "source": SOURCE.as_posix(), "source_sha256": identity,
                "functions": module.scalar_function_catalog()}
    names = set()
    for entry in data["functions"]:
        if not 0 < entry["min_args"] <= entry["max_args"] <= 128:
            raise ValueError("invalid scalar arity")
        if entry["external_engine_invoked"] is not False or entry["execution_provider"] != "shared_shardloom_native":
            raise ValueError("invalid scalar execution boundary")
        for name in [entry["name"], *entry["aliases"]]:
            if name in names or name != name.lower() or not name.isidentifier():
                raise ValueError("duplicate or invalid scalar name")
            names.add(name)
    if not names:
        raise ValueError("empty scalar function registry")
    return data


def render(data: dict) -> str:
    def cell(value):
        return str(value).replace("|", "\\|").replace("\n", " ")
    lines = ["<!-- SPDX-License-Identifier: Apache-2.0 -->", "",
        "# Native scalar functions", "",
        "Generated by `scripts/write_native_function_reference.py` from the shared native",
        "definitions used by SQL intake, type/null binding and kernel selection.",
        "`shardloom.functions.catalog()` returns these facts without creating a context or reading data.",
        "This is a source reference. Aggregates, windows, casts and nested constructors have separate contracts.",
        "All listed functions execute within ShardLoom. The decoded reference-support flag in the",
        "[JSON catalog](native-scalar-functions.json) describes a test oracle, not an execution fallback.",
        "", f"Definition source SHA-256: `{data['source_sha256']}`.", "",
        "| Function | Aliases | Arguments | Values and types | Null behavior |",
        "| --- | --- | --- | --- | --- |"]
    for entry in data["functions"]:
        arity = str(entry["min_args"]) if entry["min_args"] == entry["max_args"] else f"{entry['min_args']}–{entry['max_args']}"
        aliases = ", ".join(f"`{name}`" for name in entry["aliases"]) or "—"
        lines.append(f"| `{entry['name']}` | {aliases} | {arity} | {cell(entry['summary'])} {cell(entry['type_rule'])} | {cell(entry['null_rule'])} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--native-library", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = snapshot(ROOT, args.native_library)
    files = {TARGET: json.dumps(data, indent=2, ensure_ascii=False) + "\n",
             TARGET.with_suffix(".md"): render(data)}
    if args.check:
        stale = [str(path) for path, text in files.items()
                 if not (ROOT / path).is_file() or (ROOT / path).read_text() != text]
        if stale:
            raise ValueError("stale native scalar reference: " + ", ".join(stale))
        print("Native scalar reference is current.")
    else:
        for path, text in files.items():
            (ROOT / path).write_text(text)
        print("Updated native scalar reference.")


if __name__ == "__main__":
    main()
