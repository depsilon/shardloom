def names_for_audience(audience: str) -> tuple[str, ...]:
    """Return the stable, sorted names assigned to one explicit audience."""

    return tuple(
        sorted(name for name, (_, value) in EXPORTS.items() if value == audience)
    )


def resolve_export(name: str) -> object:
    """Resolve one assigned export without importing any module until requested."""

    try:
        module_name, _audience = EXPORTS[name]
    except KeyError as error:
        raise AttributeError(f"module 'shardloom' has no attribute {name!r}") from error
    module = import_module(f".{module_name}", "shardloom")
    return getattr(module, name)
